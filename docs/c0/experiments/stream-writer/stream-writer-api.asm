SWIMGBY EQU 119
SWDECBY  EQU 70
SWIMGCAP   EQU 0E300H       ; retained-CCP TPA: $0100..$E400
SWSPCAP      EQU 1024        ; spool bytes; deliberately greater than 16 sites
SWSECLEN EQU 51

SWINIT:
        PUSH IX
        PUSH IY
        LD (SWSTPTR),HL
        LD (SWSPPTR),DE
        LD HL,(SWSTPTR)
        LD DE,RPFCB
        LD BC,36
        LDIR
        LD HL,(SWSPPTR)
        LD DE,SWPFCB
        LD BC,36
        LDIR
        CALL SWZFCBS
        XOR A
        LD (SWERR),A
        LD (SWSTATE),A
        LD (SWDECPOS),A
        LD (SWDECPOS+1),A
        LD (SWOUTIDX),A
        LD (SWOUTIDX+1),A
        LD (SWLEN),A
        LD (SWLEN+1),A
        LD (SWIMGCNT),A
        LD (SWIMGCNT+1),A
        LD (SWIMGPTR),A
        LD (SWIMGPTR+1),A
        LD (SWICLEFT),A
        LD (SWIMGOFF),A
        LD (SWIMGOFF+1),A
        LD (SWTOTAL),A
        LD (SWTOTAL+1),A
        LD (SWSPIDX),A
        LD (SWSPIDX+1),A
        LD (SWSLEN),A
        LD (SWSLEN+1),A
        LD (SWPEND),A
        LD (SWPEND+1),A
        LD (SWPCTS),A
        LD (SWPCTS+1),A
        LD (SWRECS),A
        LD (SWRECS+1),A
        LD (SWCOUNT),A
        LD (SWCOUNT+1),A
        LD (SWDMA),A
        LD (SWRIDX),A
        LD (SWRIDX+1),A
        LD (SWRLEFT),A
        LD (SWRLEFT+1),A
        LD (SWCRC),A
        LD (SWCRC+1),A
        LD (SWFCB33),A
        LD (SWFCB34),A
        LD (SWFCB35),A
        JP SWRETOK

SWDECB:
        PUSH IX
        PUSH IY
        LD (SWARG),A
        CALL SWEVOK
        JP C,SWRETERR
        LD A,(SWSTATE)
        OR A
        JP NZ,SWBADST
        LD HL,(SWDECPOS)
        LD DE,SWDECBY
        OR A
        SBC HL,DE
        JP NC,SWCAPERR
        LD A,(SWARG)
        CALL SWOUTB
        JP C,SWRETERR
        LD HL,(SWDECPOS)
        INC HL
        LD (SWDECPOS),HL
        JP SWRETOK

SWDECEND:
        PUSH IX
        PUSH IY
        CALL SWEVOK
        JP C,SWRETERR
        LD A,(SWSTATE)
        OR A
        JP NZ,SWBADST
        LD HL,(SWDECPOS)
        LD DE,SWDECBY
        OR A
        SBC HL,DE
        JP NZ,SWCAPERR
        LD A,1
        LD (SWSTATE),A
        LD A,3
        LD (SWRECS),A       ; BEGIN, REGION, SECTION are the fixed fixture.
        XOR A
        LD (SWRECS+1),A
        JP SWRETOK

SWIMGB:
        PUSH IX
        PUSH IY
        LD (SWARG),A
        CALL SWEVOK
        JP C,SWRETERR
        LD A,(SWSTATE)
        CP 1
        JP NZ,SWBADST
        LD HL,(SWTOTAL)
        LD DE,SWIMGCAP
        INC HL
        LD A,H
        OR L
        JP Z,SWCAPERR
        OR A
        SBC HL,DE
        JP C,SWIMGOK
        JP Z,SWIMGOK
        JP SWCAPERR
SWIMGOK:
        LD HL,(SWIMGCNT)
        LD DE,SWIMAGE
        ADD HL,DE
        LD A,(SWARG)
        LD (HL),A
        LD HL,(SWIMGCNT)
        INC HL
        LD (SWIMGCNT),HL
        LD HL,(SWTOTAL)
        INC HL
        LD (SWTOTAL),HL
        LD HL,(SWIMGCNT)
        LD DE,SWIMGBY
        OR A
        SBC HL,DE
        JP NZ,SWRETOK
        CALL SWEMIT
        JP C,SWRETERR
        JP SWRETOK

SWPATCH:
        PUSH IX
        PUSH IY
        LD (SWPOFF),HL
        LD (SWPSRC),DE
        LD A,B
        LD (SWPLEN),A
        CALL SWEVOK
        JP C,SWRETERR
        LD A,(SWSTATE)
        CP 1
        JP NZ,SWBADST
        LD A,(SWPLEN)
        OR A
        JP Z,SWPCAP
        CP 5
        JP NC,SWPCAP
        LD HL,(SWPOFF)
        LD E,A
        LD D,0
        ADD HL,DE
        JP C,SWPCAP
        LD DE,SWIMGCAP
        OR A
        SBC HL,DE
        JP C,SWPOK
        JP Z,SWPOK
        JP SWPCAP
SWPOK:
        LD A,(SWPLEN)
        LD E,A
        LD D,0
        LD HL,(SWSLEN)
        LD BC,9
        ADD HL,BC
        JP C,SWPCAP
        ADD HL,DE
        JP C,SWPCAP
        LD BC,SWSPCAP
        OR A
        SBC HL,BC
        JP C,SWSPBOK
        JP Z,SWSPBOK
        JP SWPCAP
SWSPBOK:
        LD HL,(SWPOFF)
        LD A,(SWPLEN)
        LD E,A
        LD D,0
        ADD HL,DE
        LD DE,(SWPEND)
        OR A
        SBC HL,DE
        JP C,SWPWRITE
        JP Z,SWPWRITE
        LD HL,(SWPOFF)
        LD A,(SWPLEN)
        LD E,A
        LD D,0
        ADD HL,DE
        LD (SWPEND),HL
SWPWRITE:
        LD A,7
        CALL SWSPBYTE
        JP C,SWRETERR
        LD A,(SWPLEN)
        ADD A,6
        CALL SWSPBYTE
        JP C,SWRETERR
        XOR A
        CALL SWSPBYTE
        JP C,SWRETERR
        LD A,1
        CALL SWSPBYTE
        JP C,SWRETERR
        XOR A
        CALL SWSPBYTE
        JP C,SWRETERR
        LD HL,(SWPOFF)
        LD A,L
        CALL SWSPBYTE
        JP C,SWRETERR
        LD HL,(SWPOFF)      ; SWSPBYTE uses HL for its buffered output index.
        LD A,H
        CALL SWSPBYTE
        JP C,SWRETERR
        XOR A
        CALL SWSPBYTE
        JP C,SWRETERR
        XOR A
        CALL SWSPBYTE
        JP C,SWRETERR
        LD A,(SWPLEN)
        LD (SWPLEFT),A
SWPCOPY:
        LD HL,(SWPSRC)
        LD A,(HL)
        INC HL
        LD (SWPSRC),HL
        CALL SWSPBYTE
        JP C,SWRETERR
        LD A,(SWPLEFT)
        DEC A
        LD (SWPLEFT),A
        JP NZ,SWPCOPY
        LD HL,(SWPCTS)
        INC HL
        LD (SWPCTS),HL
        JP SWRETOK

SWFINAL:
        PUSH IX
        PUSH IY
        CALL SWEVOK
        JP C,SWRETERR
        LD A,(SWSTATE)
        CP 1
        JP NZ,SWBADST
        LD HL,(SWTOTAL)
        LD A,H
        OR L
        JP Z,SWCAPERR
        CALL SWEMIT
        JP C,SWRETERR
        CALL SWFLUSH
        JP C,SWRETERR
        LD HL,(SWPEND)
        LD DE,(SWTOTAL)
        OR A
        SBC HL,DE
        JP C,SWPCHECK
        JP Z,SWPCHECK
        JP SWPCAP
SWPCHECK:
        LD HL,(SWLEN)
        LD (RPLIMIT),HL
        LD HL,SWLENS
        LD DE,(SWTOTAL)
        LD (HL),E
        INC HL
        LD (HL),D
        INC HL
        XOR A
        LD (HL),A
        INC HL
        LD (HL),A
        LD A,(RPFCB+33)
        LD (SWFCB33),A
        LD A,(RPFCB+34)
        LD (SWFCB34),A
        LD A,(RPFCB+35)
        LD (SWFCB35),A
        LD HL,SWSECLEN
        LD DE,SWLENS
        LD B,4
        CALL RPATCH
        JP NC,SWSECOK
        LD (SWERR),A
        JP SWRETERR
SWSECOK:
        CALL SWRESTF
        CALL SWRLOAD
        JP C,SWRETERR
        CALL SWCOPYSP
        JP C,SWRETERR
        CALL SWLAYOUT
        JP C,SWRETERR
        CALL SWFLUSH
        JP C,SWRETERR
        CALL SWRLOAD
        JP C,SWRETERR
        CALL SWCRCRD
        JP C,SWRETERR
        CALL SWCOMMIT
        JP C,SWRETERR
        LD A,2
        LD (SWSTATE),A
        JP SWRETOK

SWABORT:
        PUSH IX
        PUSH IY
        LD A,(SWERR)
        OR A
        JP NZ,SWABDONE
        LD A,6
        LD (SWERR),A
SWABDONE:
        LD A,3
        LD (SWSTATE),A
        JP SWRETERR

